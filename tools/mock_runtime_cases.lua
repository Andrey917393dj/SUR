-- Deterministic mock contract self-tests; no Roblox/Xeno contact.
-- Intentional failure cases must remain failures even inside nested pcall.
return function(mock)
  local ok, err=mock.run([[count=0; worker=task.spawn(function() count=count+1; task.wait(0); count=count+1 end)]],false)
  assert(ok,err); assert(mock.env.count==1); assert(mock.activeTasks()==1)
  assert(mock.advance(0,100)); assert(mock.env.count==1)
  assert(mock.advance(0.01,100)); assert(mock.env.count==1)
  assert(mock.advance(0.02,100)); assert(mock.env.count==2 and mock.activeTasks()==0)
  mock.run([[worker=task.spawn(function() task.wait(10); error('should never resume') end)]],false)
  mock.env.task.cancel(mock.env.worker); assert(mock.activeTasks()==0); assert(mock.advance(12)); assert(#mock.errors==0)
  mock.run([[worker=task.spawn(function() task.wait(0.1); error('later failure') end)]],false)
  assert(not mock.advance(0.2)); assert(#mock.errors==1 and mock.errors[1]:find('later failure'))
  mock.run([[worker=task.spawn(function() while true do task.wait(0) end end)]],false)
  assert(not mock.advance(100,1)); assert(#mock.errors==1); mock.env.task.cancel(mock.env.worker)
  mock.run('',false)
  local s=mock.signal(); local n=0
  local c=s:Connect(function() n=n+1 end); c:Disconnect(); s:Fire(); assert(n==0)
  s:Once(function() n=n+1; s:Fire() end); s:Fire(); assert(n==1 and mock.activeConnections()==0)
  local worker=mock.env.task.spawn(function() n=s:Wait() end); assert(mock.activeTasks()==1); s:Fire(7); assert(n==7 and mock.activeTasks()==0)
  worker=mock.env.task.spawn(function() s:Wait() end); mock.env.task.cancel(worker); assert(mock.activeTasks()==0); assert(mock.runUntilIdle())
  s:Connect(function() error('event failure') end); s:Fire(); assert(mock.errors[1]:find('event failure'))
  mock.run('',false)
  local parent=mock.newInstance('Model','Parent'); local child=mock.newInstance('Part','Child'); child.Parent=parent
  local observed=0; local sig=child:GetPropertyChangedSignal('Name'); assert(sig==child:GetPropertyChangedSignal('Name')); sig:Connect(function() observed=observed+1 end)
  child.Name='Renamed'; assert(observed==1)
  local external=mock.newInstance('Part','External')
  local link=mock.newInstance('Weld','Link'); link.Part0=child; link.Part1=external; link.Parent=parent
  parent.PrimaryPart=child; parent:SetAttribute('number',42)
  local clone=parent:Clone(); assert(clone.PrimaryPart==clone.Renamed and clone.Link.Part0==clone.Renamed and clone.Link.Part1==external and clone:GetAttribute('number')==42)
  parent.Archivable=false; assert(parent:Clone()==nil)
  parent:Destroy(); assert(child.Parent==nil and link.Parent==nil and #parent:GetChildren()==0 and mock.activeConnections()==0)
  local env=mock.env; local cf=env.CFrame.new(10,0,0)*env.CFrame.Angles(0,math.pi/2,0)
  local p=(cf*env.CFrame.new(0,-3,4)).Position; assert(math.abs(p.X-14)<1e-9 and p.Y==-3 and math.abs(p.Z)<1e-9)
  local rel=cf:ToObjectSpace(cf*env.CFrame.new(0,-3,4)); assert((rel.Position-env.Vector3.new(0,-3,4)).Magnitude<1e-9)
  assert(math.abs(env.Color3.fromRGB(255,0,128).R-1)<1e-9)
  local h=mock.newInstance('Humanoid','Humanoid'); h.Health=80; h.MaxHealth=40; assert(h.Health==40)
  mock.env.game:GetService('Debris'):AddItem(external,1); assert(mock.activeTasks()==0); assert(mock.advance(2)); assert(external.__destroyed)
  mock.run('',false)
  local timeoutResult='pending'; local timed=mock.signal()
  mock.env.task.spawn(function() timeoutResult=timed:Wait(0.1) end)
  assert(mock.advance(0.2)); assert(timeoutResult==nil and mock.activeTasks()==0)
  local ok, err=mock.run('while true do end',false)
  assert(not ok and err:find('instruction budget exhausted') and mock.activeTasks()==0)
  local ok, err=mock.run('task.spawn(function() while true do end end)',false)
  assert(not ok and err:find('instruction budget exhausted') and mock.activeTasks()==0)
  local ok, err=mock.run('pcall(function() while true do end end)',false)
  assert(not ok and err:find('instruction budget exhausted') and mock.activeTasks()==0)
  mock.run('',false)
  local swallowed=mock.signal()
  swallowed:Once(function() pcall(function() while true do end end) end)
  swallowed:Fire()
  assert(#mock.errors==1 and mock.errors[1]:find('instruction budget exhausted') and mock.activeTasks()==0)
  print('Mock self-semantics: PASS')
end
